// ვიზუალური გასწრებები: ბოლიდები რბოლისას ერთმანეთს უსწრებენ.
// მხოლოდ ხატვაა — შედეგებს (crash) ჰეშ-ჯაჭვი წყვეტს და ამაზე არაფერია დამოკიდებული.
// seed რაუნდის ჰეშიდან მოდის, ამიტომ ყველა მოთამაშე ერთსა და იმავე გასწრებებს ხედავს.

/** სასტარტო ბადე: ბოლიდის სიგრძის ერთეულებში (წინ = +) */
export const GRID = [0, 0.35, -0.26];
/** რამდენად შორს შეიძლება წავიდეს ბოლიდი საშუალოდან (ბოლიდის სიგრძეებში) */
export const SPREAD = 1.25;
const RAMP_S = 1.6;   // სტარტიდან რამდენ წამში იწყება ბრძოლა

/** FNV-1a — ტექსტიდან 32-ბიტიანი seed */
export function seedFrom(str) {
  let h = 0x811c9dc5;
  for (const ch of String(str)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return h >>> 0;
}

// mulberry32 — დეტერმინისტური შემთხვევითი რიცხვები seed-იდან
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** რაუნდის ტალღები: თითო ბოლიდს სამი სინუსოიდა (სიხშირე, ფაზა, ამპლიტუდა) */
export function racePlan(seed) {
  const r = rng(seed);
  return [0, 1, 2].map(() => [0, 1, 2].map(k => ({
    w: 0.55 + k * 0.35 + r() * 0.4,          // რად/წმ — პერიოდი ~3.5–11 წმ
    p: r() * Math.PI * 2,
    a: [0.55, 0.3, 0.15][k] * (0.8 + r() * 0.4)
  })));
}

const smooth = x => (x <= 0 ? 0 : x >= 1 ? 1 : x * x * (3 - 2 * x));

/**
 * ბოლიდის წინსვლა საშუალოსთან შედარებით (ბოლიდის სიგრძეებში) რბოლის t წამზე.
 * t = 0-ზე — ზუსტად სასტარტო ბადე; შემდეგ თანდათან იწყება გასწრებები.
 * სამივე ბოლიდის ტალღების საშუალო გამოკლებულია, რომ ჯგუფი მთლიანად კამერას არ გაექცეს.
 */
export function leadAt(plan, car, t) {
  const wave = i => plan[i].reduce((s, h) => s + h.a * (Math.sin(h.w * t + h.p) - Math.sin(h.p)), 0);
  const mean = (wave(0) + wave(1) + wave(2)) / 3;
  return GRID[car] + smooth(t / RAMP_S) * SPREAD * (wave(car) - mean);
}
